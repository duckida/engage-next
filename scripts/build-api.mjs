import { build } from "esbuild";

/**
 * Precompile the serverless entry point to plain JavaScript.
 *
 * Vercel would otherwise hand the raw .ts files to Node, which only strips
 * types (it cannot handle parameter properties, enums or namespaces). Bundling
 * here makes the deployed function independent of Node's TS support.
 */
await build({
  entryPoints: ["server/vercel.ts"],
  outfile: "api/index.js",
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  // Keep runtime deps external; Vercel installs them from package.json.
  packages: "external",
  banner: {
    js: [
      "// Generated by scripts/build-api.mjs — do not edit.",
      "// Kept in ESM so the bundle can require() CommonJS dependencies.",
      "import { createRequire as __createRequire } from 'node:module';",
      "const require = __createRequire(import.meta.url);",
    ].join("\n"),
  },
  logLevel: "info",
});

console.log("api/index.js built");
